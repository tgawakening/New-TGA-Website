CREATE TABLE `SirahScholarshipApplication` (
  `id` VARCHAR(191) NOT NULL,
  `fullName` VARCHAR(120) NOT NULL,
  `email` VARCHAR(254) NOT NULL,
  `phone` VARCHAR(32) NOT NULL,
  `countryCode` VARCHAR(2) NOT NULL,
  `courseSlug` VARCHAR(191) NOT NULL,
  `batchCode` VARCHAR(191) NOT NULL,
  `arrangementType` VARCHAR(24) NOT NULL,
  `requestedAmountMinor` INTEGER NULL,
  `currency` VARCHAR(3) NOT NULL,
  `reason` TEXT NOT NULL,
  `documentName` VARCHAR(191) NULL,
  `documentData` LONGBLOB NULL,
  `status` VARCHAR(16) NOT NULL DEFAULT 'PENDING',
  `reviewedBy` VARCHAR(320) NULL,
  `reviewedAt` DATETIME(3) NULL,
  `reviewNotes` TEXT NULL,
  `approvedFeeMinor` INTEGER NULL,
  `approvedMonthlyMinor` INTEGER NULL,
  `orderId` VARCHAR(191) NULL,
  `notificationState` VARCHAR(16) NULL,
  `createdBy` VARCHAR(320) NULL,
  `createdAt` DATETIME(3) NOT NULL DEFAULT CURRENT_TIMESTAMP(3),
  `updatedAt` DATETIME(3) NOT NULL,
  INDEX `SirahScholarshipApplication_status_createdAt_idx` (`status`, `createdAt`),
  INDEX `SirahScholarshipApplication_email_batchCode_idx` (`email`, `batchCode`),
  INDEX `SirahScholarshipApplication_orderId_idx` (`orderId`),
  PRIMARY KEY (`id`),
  CONSTRAINT `SirahScholarshipApplication_orderId_fkey` FOREIGN KEY (`orderId`) REFERENCES `SirahOrder` (`id`) ON DELETE RESTRICT ON UPDATE CASCADE
) DEFAULT CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci;
